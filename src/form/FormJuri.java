    private void tblPesertaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblPesertaMouseClicked
        // Tampilkan penilaian sebelumnya (jika ada) agar juri bisa merevisi
        int baris = tblPeserta.getSelectedRow();
        if (baris == -1) {
            return;
        }
        String hasil = model.getValueAt(baris, 4).toString();
        if (hasil.equals("Lolos")) {
            rbLolos.setSelected(true);
        } else if (hasil.equals("Tidak Lolos")) {
            rbTidakLolos.setSelected(true);
        } else {
            buttonGroup1.clearSelection();
        }
        txtCatatan.setText(model.getValueAt(baris, 5).toString());
    }//GEN-LAST:event_tblPesertaMouseClicked

    private void btnKirimActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnKirimActionPerformed
        int baris = tblPeserta.getSelectedRow();
        if (baris == -1) {
            JOptionPane.showMessageDialog(this, "Pilih peserta di tabel terlebih dahulu!");
            return;
        }
        if (!rbLolos.isSelected() && !rbTidakLolos.isSelected()) {
            JOptionPane.showMessageDialog(this, "Pilih hasil penilaian: Lolos atau Tidak Lolos!");
            return;
        }

        String hasil = rbLolos.isSelected() ? "Lolos" : "Tidak Lolos";
        String catatan = txtCatatan.getText().trim();

        if (hasil.equals("Tidak Lolos") && catatan.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Tuliskan catatan alasan kenapa peserta tidak lolos!");
            txtCatatan.requestFocus();
            return;
        }

        String idPendaftaran = model.getValueAt(baris, 0).toString();
        String namaSiswa = model.getValueAt(baris, 1).toString();

        try {
            Connection c = Koneksi.configDB();
            // PreparedStatement supaya catatan yang mengandung tanda petik (') tetap aman
            PreparedStatement ps = c.prepareStatement(
                    "UPDATE pendaftaran SET hasil=?, catatan_juri=? WHERE id=?");
            ps.setString(1, hasil);
            ps.setString(2, catatan);
            ps.setString(3, idPendaftaran);
            ps.executeUpdate();
            JOptionPane.showMessageDialog(this, "Penilaian untuk " + namaSiswa + " (" + hasil
                    + ") berhasil dikirim.\nSiswa akan menerima pemberitahuan saat login.");
            loadDataPeserta();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal menyimpan penilaian: " + e.getMessage());
        }
    }//GEN-LAST:event_btnKirimActionPerformed

